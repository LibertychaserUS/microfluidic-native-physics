def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for chunk in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def sig6(value: float) -> float:
    return float(f"{value:.6g}")


def tuple_keys(frame: pd.DataFrame, columns: list[str]) -> list[tuple[float, ...]]:
    values = frame[columns].to_numpy(dtype=float)
    return [tuple(sig6(v) for v in row) for row in values]


def match_tables(upstream: pd.DataFrame, reference: pd.DataFrame, reference_labels: list[str]) -> dict:
    """Match upstream rows to reference rows on the eight rounded features (protocol G0)."""

    up_keys = tuple_keys(upstream, UPSTREAM_FEATURES)
    ref_keys = tuple_keys(reference, [COLUMN_MAP[c] for c in UPSTREAM_FEATURES])
    ref_index: dict[tuple, list[int]] = {}
    for index, key in enumerate(ref_keys):
        ref_index.setdefault(key, []).append(index)
    up_index: dict[tuple, list[int]] = {}
    for index, key in enumerate(up_keys):
        up_index.setdefault(key, []).append(index)
    matched_ref_rows = []
    labels = []
    max_rel = {column: 0.0 for column in NON_FEATURE_MAPPED}
    for index, key in enumerate(up_keys):
        hits = ref_index.get(key)
        if not hits:
            matched_ref_rows.append(-1)
            labels.append("unmatched")
            continue
        ref_row = hits[0]
        matched_ref_rows.append(ref_row)
        labels.append(reference_labels[ref_row])
        for column in NON_FEATURE_MAPPED:
            a = float(upstream.iloc[index][column])
            b = float(reference.iloc[ref_row][COLUMN_MAP[column]])
            if not (np.isfinite(a) and np.isfinite(b)):
                continue
            max_rel[column] = max(max_rel[column], abs(a - b) / max(abs(b), 1e-12))
    matched_up = int(sum(1 for r in matched_ref_rows if r >= 0))
    matched_ref = int(sum(1 for key in ref_keys if key in up_index))
    frac_up = matched_up / len(upstream)
    frac_ref = matched_ref / len(reference)
    same = bool(frac_up >= 0.99 and frac_ref >= 0.99 and max(max_rel.values()) <= 1e-6)
    return {
        "n_upstream": int(len(upstream)),
        "n_reference": int(len(reference)),
        "matched_upstream_rows": matched_up,
        "matched_reference_rows": matched_ref,
        "fraction_upstream_matched": frac_up,
        "fraction_reference_matched": frac_ref,
        "duplicate_feature_tuples_upstream": int(sum(1 for v in up_index.values() if len(v) > 1)),
        "duplicate_feature_tuples_reference": int(sum(1 for v in ref_index.values() if len(v) > 1)),
        "max_relative_difference_matched": max_rel,
        "label_counts": {label: int(labels.count(label)) for label in sorted(set(labels))},
        "declared_same_table": same,
        "_labels": labels,
        "_ref_rows": matched_ref_rows,
    }


def build_variant(name: str, seed: int) -> tuple[object, bool]:
    """Return (model, scale_inputs) for the ENV-A variants of protocol Section 5."""

    import dafd_reproduction as DAFD  # noqa: N811

    if name == "M0":
        return DAFD.build_model(seed), False
    if name == "M1":
        return XGBRegressor(tree_method="hist", random_state=seed, n_jobs=1), False
    if name == "M2":
        return XGBRegressor(tree_method="hist", random_state=seed, n_jobs=1), True
    if name == "M3":
        return XGBRegressor(tree_method="hist", base_score=0.5, random_state=seed, n_jobs=1), True
    raise ValueError(name)


def fit_predict_variant(name: str, seed: int, x_train, y_train, x_test) -> np.ndarray:
    model, scale = build_variant(name, seed)
    x_train = np.asarray(x_train, dtype=float)
    x_test = np.asarray(x_test, dtype=float)
    if scale:
        scaler = StandardScaler().fit(x_train)
        x_train = scaler.transform(x_train)
        x_test = scaler.transform(x_test)
    model.fit(x_train, np.asarray(y_train, dtype=float))
    return np.asarray(model.predict(x_test), dtype=float)


def rate_mape(frame: pd.DataFrame, predicted_um: np.ndarray, pi_constant: float) -> float:
    import dafd_reproduction as DAFD  # noqa: N811

    flow_m3_s = frame[DAFD.DISPERSED_FLOW].to_numpy(dtype=float) * 1e-9 / 3600.0
    diameter_m = predicted_um * 1e-6
    predicted_rate = 6.0 * flow_m3_s / (pi_constant * diameter_m**3)
    actual = frame[DAFD.TARGET_RATE].to_numpy(dtype=float)
    return float(100.0 * np.mean(np.abs(actual - predicted_rate) / np.abs(actual)))


def unit_of(task_id: str) -> str:
    if task_id.startswith("row_random_reproduction"):
        return "U1_random"
    if task_id.startswith("exact_input_dependency_group"):
        return "U2_exact_input"
    if task_id.startswith("geometry_dependency_group"):
        return "U3_geometry"
    if task_id.startswith("device_fluid_dependency_group"):
        return "U4_device_fluid"
    if task_id == "external_full_training":
        return "U5_external"
    raise ValueError(task_id)


